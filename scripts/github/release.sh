#!/usr/bin/env bash
# ==============================================================================
# DF71 Standardized GitHub Release Script
# Usage: bash scripts/github/release.sh [patch|minor|major] [--dry-run]
# ==============================================================================
set -euo pipefail

BUMP_TYPE="${1:-patch}"
DRY_RUN=false
for arg in "$@"; do
  if [ "$arg" = "--dry-run" ]; then
    DRY_RUN=true
  fi
done

echo "🔍 [df71:release] Step 1: Pre-task stage and git hygiene check..."
if command -v df71 >/dev/null 2>&1; then
  df71 stage-check --pre-task
elif [ -f bin/factory.js ]; then
  node bin/factory.js stage-check --pre-task
fi

echo "🧪 [df71:release] Step 2: Executing full Dark Factory verification gate..."
if [ -f Makefile ]; then
  make df71:check
else
  pnpm run df71:check
fi

echo "📦 [df71:release] Step 3: Extracting version and changelog notes..."
if [ ! -f package.json ]; then
  echo "❌ Error: package.json not found"
  exit 1
fi

CURRENT_VERSION=$(node -p "require('./package.json').version")
echo "  Current version: ${CURRENT_VERSION}"

# Calculate next semver
IFS='.' read -r major minor patch <<< "${CURRENT_VERSION}"
case "${BUMP_TYPE}" in
  major)
    NEXT_VERSION="$((major + 1)).0.0"
    ;;
  minor)
    NEXT_VERSION="${major}.$((minor + 1)).0"
    ;;
  patch)
    NEXT_VERSION="${major}.${minor}.$((patch + 1))"
    ;;
  *)
    NEXT_VERSION="${BUMP_TYPE#v}"
    ;;
esac
TAG_NAME="v${NEXT_VERSION}"
echo "  Target release: ${TAG_NAME}"

# Extract release notes from CHANGELOG.md
NOTES_FILE=$(mktemp)
if [ -f CHANGELOG.md ]; then
  awk "/^## \\[${NEXT_VERSION}\\]/{flag=1; next} /^## \\[[0-9]/{flag=0} flag" CHANGELOG.md > "${NOTES_FILE}" || true
fi

if [ ! -s "${NOTES_FILE}" ]; then
  echo "Release ${TAG_NAME} generated by df71 release automation." > "${NOTES_FILE}"
fi

if [ "${DRY_RUN}" = true ]; then
  echo "🔎 [DRY RUN] Would update version to ${NEXT_VERSION}, tag ${TAG_NAME}, push to origin, and create GitHub Release:"
  cat "${NOTES_FILE}"
  rm -f "${NOTES_FILE}"
  exit 0
fi

echo "📝 [df71:release] Step 4: Bumping version and committing..."
npm version "${NEXT_VERSION}" --no-git-tag-version

if [ -f Makefile ]; then
  make build
fi

git add package.json
if [ -f CHANGELOG.md ]; then
  git add CHANGELOG.md
fi
if [ -d dist ]; then
  git add dist
fi

git commit -m "chore(release): ${TAG_NAME}" || true
git tag -a "${TAG_NAME}" -m "Release ${TAG_NAME}"

echo "🚀 [df71:release] Step 5: Pushing commit and tag to origin..."
git push origin main
git push origin "${TAG_NAME}"

echo "🎉 [df71:release] Step 6: Creating GitHub Release via gh CLI..."
gh release create "${TAG_NAME}" \
  --title "Release ${TAG_NAME}" \
  --notes-file "${NOTES_FILE}"

rm -f "${NOTES_FILE}"
echo "✅ [df71:release] Successfully published ${TAG_NAME} on GitHub!"
